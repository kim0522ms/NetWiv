using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Emit;
using NetWiv.Build.Frontend;
using NetWiv.Generators;
using Xunit;

namespace NetWiv.Generators.Tests;

public sealed class CSharpClientTests
{
    // A shared contracts library: the DTO and the JSON context both projects reference.
    private const string Contracts = """
        using System.Text.Json.Serialization;
        public sealed record Greeting(string Message, int Count);
        [JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase)]
        public abstract class SharedContext : JsonSerializerContext {
            protected SharedContext() : base(null) { }
            public static SharedContext Default => throw new System.Exception("Application must not execute during export");
        }
        """;

    private const string App = """
        using System.Threading.Tasks;
        using NetWiv;
        [assembly: GenerateFrontendBindings]
        [assembly: CommandJsonContext(typeof(SharedContext))]
        public sealed record Local(int Value);
        public static class Commands {
            [Command] public static Greeting Greet(string name, AppHandle app) => throw null!;
            [Command] public static Task<string[]> List(int? limit, string @class) => throw null!;
            [Command] public static void SmokeDone(string result) { }
            [Command] public static Local Echo(Local value) => value;
        }
        """;

    [Fact]
    public void EmitsTypedCallsForSharedTypesAndExplainsSkippedCommands()
    {
        var client = Client(App);
        Assert.StartsWith("// Generated by NetWiv. Do not edit.\n", client, StringComparison.Ordinal);
        Assert.Contains("public async global::System.Threading.Tasks.Task<global::Greeting> GreetAsync(string name, global::System.Threading.CancellationToken cancellationToken = default)", client, StringComparison.Ordinal);
        Assert.Contains("args[\"name\"] = ", client, StringComparison.Ordinal);
        Assert.Contains("InvokeAsync(\"greet\", args, cancellationToken)", client, StringComparison.Ordinal);
        Assert.Contains("Task<string[]> ListAsync(int? limit, string @class, ", client, StringComparison.Ordinal);
        Assert.Contains("args[\"class\"] = global::System.Text.Json.JsonSerializer.SerializeToNode(@class, ", client, StringComparison.Ordinal);
        Assert.Contains("public async global::System.Threading.Tasks.Task SmokeDoneAsync(string result, ", client, StringComparison.Ordinal);
        Assert.DoesNotContain("AppHandle", client, StringComparison.Ordinal);
        Assert.Contains("//   echo: Local is declared in the app or in a NetWiv package", client, StringComparison.Ordinal);
        Assert.DoesNotContain("EchoAsync", client, StringComparison.Ordinal);
    }

    [Fact]
    public void GeneratedClientCompilesInAFrontendThatReferencesOnlyTheContracts()
    {
        var contracts = Reference("Contracts", Contracts);
        var frontend = CSharpCompilation.Create("Frontend", [CSharpSyntaxTree.ParseText(Client(App), new CSharpParseOptions(LanguageVersion.CSharp12))],
            PlatformReferences().Append(contracts).Append(MetadataReference.CreateFromFile(typeof(Microsoft.JSInterop.IJSRuntime).Assembly.Location)),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        Assert.DoesNotContain(frontend.GetDiagnostics(), diagnostic => diagnostic.Severity >= DiagnosticSeverity.Warning);
    }

    [Fact]
    public void SkipsEveryCommandWhenTheJsonContextLivesInTheApp()
    {
        var client = Client("""
            using System.Text.Json.Serialization;
            using NetWiv;
            [assembly: GenerateFrontendBindings]
            [assembly: CommandJsonContext(typeof(AppContext))]
            public abstract class AppContext : JsonSerializerContext {
                protected AppContext() : base(null) { }
                public static AppContext Default => throw new System.Exception();
            }
            public static class Commands { [Command] public static string Greet(string name) => name; }
            """);
        Assert.Contains("//   greet: AppContext is declared in the app, not in a shared project", client, StringComparison.Ordinal);
        Assert.DoesNotContain("GreetAsync", client, StringComparison.Ordinal);
    }

    [Fact]
    public void WritesTheClientOnlyOverNetWivGeneratedFiles()
    {
        var directory = Directory.CreateTempSubdirectory("netwiv-csharp-client-").FullName;
        try
        {
            var bindings = new FrontendBindings("// Generated by NetWiv. Do not edit.\n", "// Generated by NetWiv. Do not edit.\n") { CSharp = "// Generated by NetWiv. Do not edit.\nnamespace N;\n" };
            bindings.WriteCSharpTo(directory);
            var path = Path.Combine(directory, "NetWivCommands.g.cs");
            Assert.Equal(bindings.CSharp, File.ReadAllText(path));
            Assert.False(File.Exists(Path.Combine(directory, "commands.js")));
            File.WriteAllText(path, "handwritten");
            Assert.Throws<InvalidOperationException>(() => bindings.WriteCSharpTo(directory));
            Assert.Throws<InvalidOperationException>(() => new FrontendBindings("a", "b").WriteCSharpTo(directory));
        }
        finally { Directory.Delete(directory, true); }
    }

    private static string Client(string app)
    {
        var compilation = CSharpCompilation.Create("DesktopApp", [CSharpSyntaxTree.ParseText(app, new CSharpParseOptions(LanguageVersion.CSharp12))],
            PlatformReferences().Append(MetadataReference.CreateFromFile(typeof(CommandAttribute).Assembly.Location)).Append(Reference("Contracts", Contracts)),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new CommandGenerator());
        driver.RunGeneratorsAndUpdateCompilation(compilation, out var updated, out var diagnostics);
        Assert.DoesNotContain(diagnostics.Concat(updated.GetDiagnostics()), diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);
        var path = Path.Combine(Path.GetTempPath(), "netwiv-csharp-client-" + Guid.NewGuid().ToString("N") + ".dll");
        try
        {
            var emitted = updated.Emit(path);
            Assert.True(emitted.Success, string.Join("\n", emitted.Diagnostics));
            return FrontendBindings.Read(path).CSharp ?? throw new InvalidOperationException("No C# client was emitted.");
        }
        finally { File.Delete(path); }
    }

    private static IEnumerable<MetadataReference> PlatformReferences()
        => ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator).Select(path => MetadataReference.CreateFromFile(path));

    private static MetadataReference Reference(string name, string source)
    {
        var compilation = CSharpCompilation.Create(name, [CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.CSharp12))], PlatformReferences(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        using var stream = new MemoryStream();
        var emitted = compilation.Emit(stream);
        Assert.True(emitted.Success, string.Join("\n", emitted.Diagnostics));
        return MetadataReference.CreateFromImage(ImmutableArray.CreateRange(stream.ToArray()), filePath: name + ".dll");
    }
}
