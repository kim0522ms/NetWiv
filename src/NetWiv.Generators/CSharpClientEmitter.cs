using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace NetWiv.Generators;

/// <summary>
/// Emits a typed C# client for a .NET frontend such as Blazor WebAssembly. The client
/// reuses the application's own DTO and JSON context types instead of redeclaring them,
/// so it is emitted only for commands whose wire types and serializer context live in an
/// assembly the frontend can reference (the BCL or a shared contracts library), never in
/// the desktop application itself.
/// </summary>
internal static class CSharpClientEmitter
{
    private const string Header = "// Generated by NetWiv. Do not edit.\n";

    // Members of the generated class that a command method must not be named after.
    private static readonly string[] Reserved = ["NetWivCommands", "InvokeAsync", "Info", "ByteArrayNode", "ReadByteArray", "ElementNode", "ReadElement"];

    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    internal static string Emit(IAssemblySymbol application, IReadOnlyList<FrontendCommand> commands)
    {
        var local = commands.Where(command => SymbolEqualityComparer.Default.Equals(command.Method.ContainingAssembly, application))
            .OrderBy(static command => command.Name, StringComparer.Ordinal).ToArray();
        var skipped = new List<string>();
        var included = new List<FrontendCommand>();
        foreach (var command in local)
        {
            var reason = Unsupported(application, command);
            if (reason is null) included.Add(command);
            else skipped.Add(command.Name + ": " + reason);
        }
        var methods = new StringBuilder();
        var names = MethodNames(included);
        foreach (var command in included) AppendMethod(methods, command, names[command]);

        var source = new StringBuilder(Header)
            .Append("// <auto-generated />\n#nullable enable\n\nnamespace NetWiv.Generated;\n\n");
        if (skipped.Count > 0)
        {
            source.Append("// Commands without a typed C# call. Move their parameter, result and JSON context\n")
                .Append("// types into a project that both the app and this frontend reference:\n");
            foreach (var line in skipped) source.Append("//   ").Append(OneLine(line)).Append('\n');
            source.Append('\n');
        }
        source.Append(
            "/// <summary>Typed calls to the C# commands of " + Escape(application.Name) + ".</summary>\n" +
            "/// <remarks>Register with <c>builder.Services.AddScoped&lt;NetWivCommands&gt;()</c>. Calls travel through\n" +
            "/// <c>wwwroot/netwiv.js</c>, which forwards them to <c>@netwiv/api</c>.</remarks>\n" +
            "public sealed partial class NetWivCommands\n{\n" +
            "    private readonly global::Microsoft.JSInterop.IJSRuntime _js;\n" +
            "    private global::Microsoft.JSInterop.IJSObjectReference? _module;\n\n" +
            "    public NetWivCommands(global::Microsoft.JSInterop.IJSRuntime js) => _js = js;\n")
            .Append(methods)
            .Append(Helpers(included))
            .Append(
            "\n    private async global::System.Threading.Tasks.Task<string> InvokeAsync(string command, global::System.Text.Json.Nodes.JsonObject args, global::System.Threading.CancellationToken cancellationToken)\n" +
            "    {\n" +
            "        _module ??= await global::Microsoft.JSInterop.JSRuntimeExtensions.InvokeAsync<global::Microsoft.JSInterop.IJSObjectReference>(_js, \"import\", cancellationToken, \"./netwiv.js\");\n" +
            "        return await global::Microsoft.JSInterop.JSObjectReferenceExtensions.InvokeAsync<string>(_module, \"invokeJson\", cancellationToken, command, args.ToJsonString());\n" +
            "    }\n\n" +
            "    private static global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T> Info<T>(global::System.Text.Json.Serialization.JsonSerializerContext context)\n" +
            "        => context.GetTypeInfo(typeof(T)) as global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T>\n" +
            "           ?? throw new global::System.NotSupportedException($\"Add [JsonSerializable(typeof({typeof(T).Name}))] to {context.GetType().Name}.\");\n" +
            "}\n");
        return source.ToString();
    }

    private static void AppendMethod(StringBuilder output, FrontendCommand command, string name)
    {
        var context = command.JsonContext?.ToDisplayString(TypeFormat) + ".Default";
        // Locals must not shadow or collide with the command's own parameter names.
        var taken = new HashSet<string>(command.Parameters.Select(static parameter => parameter.Name), StringComparer.Ordinal);
        var token = Unique("cancellationToken", taken);
        var args = Unique("args", taken);
        var json = Unique("json", taken);
        var parameters = command.Parameters.Select(parameter => parameter.Type.ToDisplayString(TypeFormat) + " " + Identifier(parameter.Name))
            .Append("global::System.Threading.CancellationToken " + token + " = default");
        var result = command.Result?.ToDisplayString(TypeFormat);
        output.Append("\n    /// <summary>Calls the C# command <c>").Append(Escape(command.Name)).Append("</c> (")
            .Append(Escape(command.Method.ContainingType.Name)).Append('.').Append(Escape(command.Method.Name)).Append(").</summary>\n")
            .Append("    public async global::System.Threading.Tasks.Task").Append(result is null ? "" : "<" + result + ">")
            .Append(' ').Append(name).Append('(').Append(string.Join(", ", parameters)).Append(")\n    {\n")
            .Append("        var ").Append(args).Append(" = new global::System.Text.Json.Nodes.JsonObject();\n");
        foreach (var parameter in command.Parameters)
        {
            var value = Identifier(parameter.Name);
            // byte[] and JsonElement bypass the JSON context on the C# side, exactly as the command dispatcher does.
            var node = IsByteArray(parameter.Type) ? "global::NetWiv.Generated.NetWivCommands.ByteArrayNode(" + value + ")"
                : IsJsonElement(parameter.Type) ? "global::NetWiv.Generated.NetWivCommands.ElementNode(" + value + ")"
                : "global::System.Text.Json.JsonSerializer.SerializeToNode(" + value + ", Info<" + parameter.Type.ToDisplayString(TypeFormat) + ">(" + context + "))";
            output.Append("        ").Append(args).Append('[').Append(Literal(parameter.Name)).Append("] = ").Append(node).Append(";\n");
        }
        var call = "await this.InvokeAsync(" + Literal(command.Name) + ", " + args + ", " + token + ")";
        var read = command.Result is null ? null
            : IsByteArray(command.Result) ? "global::NetWiv.Generated.NetWivCommands.ReadByteArray(" + json + ")!"
            : IsJsonElement(command.Result) ? "global::NetWiv.Generated.NetWivCommands.ReadElement(" + json + ")"
            : "global::System.Text.Json.JsonSerializer.Deserialize(" + json + ", Info<" + result + ">(" + context + "))!";
        output.Append(read is null
            ? "        " + call + ";\n"
            : "        var " + json + " = " + call + ";\n        return " + read + ";\n");
        output.Append("    }\n");
    }

    // The command dispatcher reads and writes top-level byte[] as a JSON array of numbers
    // (not System.Text.Json's base64 string) and passes JsonElement through unchanged.
    private static string Helpers(IReadOnlyList<FrontendCommand> commands)
    {
        var types = commands.SelectMany(WireTypes).ToArray();
        var helpers = new StringBuilder();
        if (types.Any(IsByteArray))
        {
            helpers.Append(
                "\n    private static global::System.Text.Json.Nodes.JsonNode? ByteArrayNode(byte[]? values)\n" +
                "    {\n" +
                "        if (values is null) return null;\n" +
                "        var array = new global::System.Text.Json.Nodes.JsonArray();\n" +
                // The JsonNode cast picks the non-generic Add; Add<T> is not trim or AOT safe.
                "        foreach (var value in values) array.Add((global::System.Text.Json.Nodes.JsonNode)global::System.Text.Json.Nodes.JsonValue.Create(value));\n" +
                "        return array;\n" +
                "    }\n\n" +
                "    private static byte[]? ReadByteArray(string json)\n" +
                "    {\n" +
                "        using var document = global::System.Text.Json.JsonDocument.Parse(json);\n" +
                "        var root = document.RootElement;\n" +
                "        if (root.ValueKind == global::System.Text.Json.JsonValueKind.Null) return null;\n" +
                "        var bytes = new byte[root.GetArrayLength()];\n" +
                "        var index = 0;\n" +
                "        foreach (var item in root.EnumerateArray()) bytes[index++] = item.GetByte();\n" +
                "        return bytes;\n" +
                "    }\n");
        }
        if (types.Any(IsJsonElement))
        {
            helpers.Append(
                "\n    private static global::System.Text.Json.Nodes.JsonNode? ElementNode(global::System.Text.Json.JsonElement value)\n" +
                "        => value.ValueKind == global::System.Text.Json.JsonValueKind.Undefined ? null : global::System.Text.Json.Nodes.JsonNode.Parse(value.GetRawText());\n\n" +
                "    private static global::System.Text.Json.JsonElement ReadElement(string json)\n" +
                "    {\n" +
                "        using var document = global::System.Text.Json.JsonDocument.Parse(json);\n" +
                "        return document.RootElement.Clone();\n" +
                "    }\n");
        }
        return helpers.ToString();
    }

    private static IEnumerable<ITypeSymbol> WireTypes(FrontendCommand command)
        => command.Parameters.Select(static parameter => parameter.Type).Concat(command.Result is null ? Array.Empty<ITypeSymbol>() : new[] { command.Result });

    private static bool IsByteArray(ITypeSymbol type)
        => type is IArrayTypeSymbol { Rank: 1, ElementType.SpecialType: SpecialType.System_Byte };

    private static bool IsJsonElement(ITypeSymbol type)
        => type.ToDisplayString() == "System.Text.Json.JsonElement";

    private static string Unique(string name, ISet<string> taken)
    {
        var candidate = name;
        for (var suffix = 2; !taken.Add(candidate); suffix++) candidate = name + suffix.ToString(System.Globalization.CultureInfo.InvariantCulture);
        return candidate;
    }

    // Reasons a command cannot get a typed C# call; null means it can.
    private static string? Unsupported(IAssemblySymbol application, FrontendCommand command)
    {
        var types = WireTypes(command).ToArray();
        foreach (var type in types)
        {
            var blocked = Blocked(application, type);
            if (blocked is not null) return blocked;
        }
        // byte[] and JsonElement bypass the serializer context, so a command that uses only those needs none.
        if (types.All(static type => IsByteArray(type) || IsJsonElement(type))) return null;
        if (command.JsonContext is null) return "no [assembly: CommandJsonContext] is declared";
        if (!Reachable(application, command.JsonContext)) return command.JsonContext.Name + " is declared in the app, not in a shared project";
        return null;
    }

    private static string? Blocked(IAssemblySymbol application, ITypeSymbol type)
    {
        switch (type)
        {
            case IArrayTypeSymbol array:
                return Blocked(application, array.ElementType);
            case INamedTypeSymbol named:
                if (!Reachable(application, named)) return named.Name + " is declared in the app or in a NetWiv package";
                foreach (var argument in named.TypeArguments)
                {
                    var blocked = Blocked(application, argument);
                    if (blocked is not null) return blocked;
                }
                return null;
            default:
                return type.Name + " is not a concrete wire type";
        }
    }

    // A frontend project can reference the BCL and shared libraries, but neither the desktop
    // app nor NetWiv's own packages, which carry the native desktop runtime.
    private static bool Reachable(IAssemblySymbol application, INamedTypeSymbol type)
    {
        if (type.DeclaredAccessibility != Accessibility.Public) return false;
        for (var parent = type.ContainingType; parent is not null; parent = parent.ContainingType)
            if (parent.DeclaredAccessibility != Accessibility.Public) return false;
        var assembly = type.ContainingAssembly;
        if (assembly is null || SymbolEqualityComparer.Default.Equals(assembly, application)) return false;
        return !assembly.Name.StartsWith("NetWiv.", StringComparison.Ordinal);
    }

    private static Dictionary<FrontendCommand, string> MethodNames(IReadOnlyList<FrontendCommand> commands)
    {
        string Preferred(FrontendCommand command)
            => command.Method.Name.EndsWith("Async", StringComparison.Ordinal) ? command.Method.Name : command.Method.Name + "Async";
        var duplicates = new HashSet<string>(commands.GroupBy(Preferred, StringComparer.Ordinal)
            .Where(static group => group.Count() > 1).Select(static group => group.Key), StringComparer.Ordinal);
        // Two methods with one name fall back to the external command name. Different command
        // names can still normalize to one identifier (foo-bar, foo_bar), and a name can match a
        // helper of the client, so a numeric suffix settles whatever collision is left.
        var taken = new HashSet<string>(Reserved, StringComparer.Ordinal);
        var names = new Dictionary<FrontendCommand, string>();
        foreach (var command in commands)
        {
            var name = duplicates.Contains(Preferred(command)) ? Pascal(command.Name) + "Async" : Preferred(command);
            var stem = name.Substring(0, name.Length - "Async".Length);
            for (var suffix = 2; !taken.Add(name); suffix++) name = stem + suffix.ToString(System.Globalization.CultureInfo.InvariantCulture) + "Async";
            names[command] = name;
        }
        return names;
    }

    private static string Pascal(string name)
    {
        var builder = new StringBuilder();
        var upper = true;
        foreach (var c in name)
        {
            if (!char.IsLetterOrDigit(c)) { upper = true; continue; }
            builder.Append(upper ? char.ToUpperInvariant(c) : c);
            upper = false;
        }
        if (builder.Length == 0 || char.IsDigit(builder[0])) builder.Insert(0, 'C');
        return builder.ToString();
    }

    // Parameters live in an async method, where the contextual keyword await is reserved too.
    private static string Identifier(string name)
        => Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None || name == "await" ? "@" + name : name;

    private static string Literal(string value)
        => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);

    // Comment text stays on one line whatever the command or type name contains.
    private static string OneLine(string value)
        => new string(value.Select(static c => char.IsControl(c) || c is '\u2028' or '\u2029' ? ' ' : c).ToArray());

    private static string Escape(string value)
        => OneLine(value).Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
