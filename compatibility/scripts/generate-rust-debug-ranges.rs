// Maintainer-only generator, built with the pinned Rust 1.95.0 compiler.
// Stdout is RustDebugStringRanges.g.cs. --oracle <path> writes the UTF-8
// Debug representation of every Unicode scalar string, one per line.
use std::io::Write;

fn main() {
    let args: Vec<_> = std::env::args().skip(1).collect();
    if args.first().map(String::as_str) == Some("--oracle") {
        assert_eq!(args.len(), 2);
        let mut output = std::io::BufWriter::new(std::fs::File::create(&args[1]).unwrap());
        for character in (0..=0x10ffff).filter_map(char::from_u32) {
            writeln!(output, "{:?}", character.to_string()).unwrap();
        }
        return;
    }
    assert!(args.is_empty());
    println!("// Generated by compatibility/scripts/generate-rust-debug-ranges.rs; do not edit.");
    println!("// Rust 1.95.0, Unicode {:?}.\nnamespace NetWiv;", char::UNICODE_VERSION);
    println!("internal static partial class RustDebugString\n{{\n    private static ReadOnlySpan<int> PrintableRanges =>\n    [");
    let mut start = None;
    for value in 0..=0x110000 {
        let printable = char::from_u32(value).is_some_and(|character| {
            format!("{:?}", character.to_string()) == format!("\"{character}\"")
        });
        match (start, printable) {
            (None, true) => start = Some(value),
            (Some(first), false) => {
                println!("        0x{first:X}, 0x{:X},", value - 1);
                start = None;
            }
            _ => {}
        }
    }
    println!("    ];\n}}");
}
