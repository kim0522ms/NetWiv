using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace NetWiv.Generators;

public sealed partial class CommandGenerator
{
    private const string FrontendCommandMarker = "NetWiv.Frontend.Commands.v1";
    private const string FrontendCommandPrefix = "NetWiv.Frontend.Command.v1:";
    private static readonly DiagnosticDescriptor InvalidFrontendMetadata = new(
        "DTOXGEN013", "Invalid referenced frontend command metadata",
        "Cannot aggregate frontend commands from '{0}': {1}; rebuild the producer with a compatible NetWiv.Generators version",
        "NetWiv.Generators", DiagnosticSeverity.Error, true);

    private static void EmitFrontendCommandMetadata(SourceProductionContext output, IEnumerable<FrontendCommand> commands)
    {
        var source = new StringBuilder("// <auto-generated />\n");
        void Add(string key, string value) => source.Append("[assembly: global::System.Reflection.AssemblyMetadataAttribute(")
            .Append(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(key, true)).Append(", ")
            .Append(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true)).AppendLine(")]");
        Add(FrontendCommandMarker, "1");
        foreach (var command in commands.Where(command => IsPublicCommand(command.Method)).OrderBy(command => command.Name, StringComparer.Ordinal))
            Add(FrontendCommandPrefix + command.Method.GetDocumentationCommentId(),
                MetadataTypeName(command.Method.ContainingType) + "\n" + command.Name);
        output.AddSource("NetWiv.FrontendCommandMetadata.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static bool AddReferencedFrontendCommands(SourceProductionContext output, Compilation compilation, List<FrontendCommand> commands)
    {
        foreach (var assembly in compilation.SourceModule.ReferencedAssemblySymbols.OrderBy(assembly => assembly.Identity.ToString(), StringComparer.Ordinal))
        {
            // Only direct compiler references participate. Aggregated dependencies are never
            // re-exported in the producer's command index.
            if (!assembly.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == "NetWiv.GenerateFrontendBindingsAttribute")) continue;
            var metadata = assembly.GetAttributes().Where(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Reflection.AssemblyMetadataAttribute")
                .Where(attribute => attribute.ConstructorArguments.Length == 2 && attribute.ConstructorArguments[0].Value is string key &&
                    (key.StartsWith("NetWiv.Frontend.Commands.", StringComparison.Ordinal) || key.StartsWith("NetWiv.Frontend.Command.", StringComparison.Ordinal))).ToArray();
            bool Invalid(string reason)
            {
                output.ReportDiagnostic(Diagnostic.Create(InvalidFrontendMetadata, Location.None, assembly.Identity.Name, reason));
                return false;
            }
            if (metadata.Any(attribute => attribute.ConstructorArguments[0].Value is string key && key != FrontendCommandMarker && !key.StartsWith(FrontendCommandPrefix, StringComparison.Ordinal)))
                return Invalid("unsupported command metadata version");
            var markers = metadata.Where(attribute => (string)attribute.ConstructorArguments[0].Value! == FrontendCommandMarker).ToArray();
            if (markers.Length != 1 || markers[0].ConstructorArguments[1].Value is not "1") return Invalid("missing, duplicate or invalid command metadata marker");
            var declarations = metadata.Where(attribute => (string)attribute.ConstructorArguments[0].Value! != FrontendCommandMarker).ToArray();
            if (declarations.Length == 0) continue;
            var jsonContext = FindJsonContext(assembly, output, out var invalidContext);
            if (invalidContext) return false;
            var seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (var attribute in declarations)
            {
                var id = ((string)attribute.ConstructorArguments[0].Value!).Substring(FrontendCommandPrefix.Length);
                if (!seen.Add(id) || attribute.ConstructorArguments[1].Value is not string value) return Invalid("missing or duplicate command declaration");
                var parts = value.Split(new[] { '\n' }, 2);
                if (parts.Length != 2 || string.IsNullOrWhiteSpace(parts[1])) return Invalid("malformed command declaration");
                var method = assembly.GetTypeByMetadataName(parts[0])?.GetMembers().OfType<IMethodSymbol>()
                    .SingleOrDefault(method => method.GetDocumentationCommentId() == id);
                if (method is null || !IsPublicCommand(method)) return Invalid("command declaration must resolve to a public accessible method: " + id);
                var commandAttribute = method.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == CommandAttributeName);
                if (commandAttribute is null) return Invalid("command declaration has no Command attribute: " + id);
                var localName = commandAttribute.ConstructorArguments.FirstOrDefault().Value as string ?? ToSnakeCase(method.Name);
                if (!TryCreateModel(output, new CommandCandidate(method, localName), jsonContext, out var model)) return false;
                if (model!.IsPluginCommand)
                {
                    var contract = method.ContainingType.AllInterfaces.First(type => type.ToDisplayString() == "NetWiv.IPlugin");
                    var property = method.ContainingType.FindImplementationForInterfaceMember(contract.GetMembers("Name").Single()) as IPropertySymbol;
                    var prefixLength = "plugin:".Length;
                    var suffix = "|" + localName;
                    if (property is null || property.IsVirtual || property.IsOverride || property.IsAbstract ||
                        !parts[1].StartsWith("plugin:", StringComparison.Ordinal) || !parts[1].EndsWith(suffix, StringComparison.Ordinal) ||
                        string.IsNullOrWhiteSpace(parts[1].Substring(prefixLength, parts[1].Length - prefixLength - suffix.Length)))
                        return Invalid("plugin route or non-virtual Name getter is invalid: " + id);
                }
                else if (parts[1] != localName) return Invalid("application route differs from its Command attribute: " + id);
                commands.Add(new FrontendCommand(parts[1], model.Parameters.Where(parameter => parameter.Injection is null)
                    .Select(parameter => parameter.Symbol).ToArray(), model.Return.ValueType, method, jsonContext));
            }
        }
        return true;
    }

    private static bool IsPublicCommand(IMethodSymbol method)
    {
        if (method.DeclaredAccessibility != Accessibility.Public) return false;
        for (var type = method.ContainingType; type is not null; type = type.ContainingType)
            if (type.DeclaredAccessibility != Accessibility.Public) return false;
        return true;
    }

    private static string MetadataTypeName(INamedTypeSymbol type)
        => type.ContainingType is { } parent ? MetadataTypeName(parent) + "+" + type.MetadataName :
            (type.ContainingNamespace.IsGlobalNamespace ? "" : type.ContainingNamespace.ToDisplayString() + ".") + type.MetadataName;
}
