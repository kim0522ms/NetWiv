using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace NetWiv.Generators;

/// <summary>
/// Emits a typed C# client for a .NET frontend such as Blazor WebAssembly. The client
/// reuses the application's own DTO and JSON context types instead of redeclaring them,
/// so it is emitted only for commands whose wire types and serializer context live in an
/// assembly the frontend can reference (the BCL or a shared contracts library), never in
/// the desktop application itself.
/// </summary>
internal static class CSharpClientEmitter
{
    private const string Header = "// Generated by NetWiv. Do not edit.\n";

    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    internal static string Emit(IAssemblySymbol application, IReadOnlyList<FrontendCommand> commands)
    {
        var local = commands.Where(command => SymbolEqualityComparer.Default.Equals(command.Method.ContainingAssembly, application))
            .OrderBy(static command => command.Name, StringComparer.Ordinal).ToArray();
        var methods = new StringBuilder();
        var skipped = new List<string>();
        var names = MethodNames(local);
        foreach (var command in local)
        {
            var reason = Unsupported(application, command);
            if (reason is not null)
            {
                skipped.Add(command.Name + ": " + reason);
                continue;
            }
            AppendMethod(methods, command, names[command]);
        }

        var source = new StringBuilder(Header)
            .Append("// <auto-generated />\n#nullable enable\n\nnamespace NetWiv.Generated;\n\n");
        if (skipped.Count > 0)
        {
            source.Append("// Commands without a typed C# call. Move their parameter, result and JSON context\n")
                .Append("// types into a project that both the app and this frontend reference:\n");
            foreach (var line in skipped) source.Append("//   ").Append(line).Append('\n');
            source.Append('\n');
        }
        source.Append(
            "/// <summary>Typed calls to the C# commands of " + Escape(application.Name) + ".</summary>\n" +
            "/// <remarks>Register with <c>builder.Services.AddScoped&lt;NetWivCommands&gt;()</c>. Calls travel through\n" +
            "/// <c>wwwroot/netwiv.js</c>, which forwards them to <c>@netwiv/api</c>.</remarks>\n" +
            "public sealed partial class NetWivCommands\n{\n" +
            "    private readonly global::Microsoft.JSInterop.IJSRuntime _js;\n" +
            "    private global::Microsoft.JSInterop.IJSObjectReference? _module;\n\n" +
            "    public NetWivCommands(global::Microsoft.JSInterop.IJSRuntime js) => _js = js;\n")
            .Append(methods)
            .Append(
            "\n    private async global::System.Threading.Tasks.Task<string> InvokeAsync(string command, global::System.Text.Json.Nodes.JsonObject args, global::System.Threading.CancellationToken cancellationToken)\n" +
            "    {\n" +
            "        _module ??= await global::Microsoft.JSInterop.JSRuntimeExtensions.InvokeAsync<global::Microsoft.JSInterop.IJSObjectReference>(_js, \"import\", cancellationToken, \"./netwiv.js\");\n" +
            "        return await global::Microsoft.JSInterop.JSObjectReferenceExtensions.InvokeAsync<string>(_module, \"invokeJson\", cancellationToken, command, args.ToJsonString());\n" +
            "    }\n\n" +
            "    private static global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T> Info<T>(global::System.Text.Json.Serialization.JsonSerializerContext context)\n" +
            "        => context.GetTypeInfo(typeof(T)) as global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T>\n" +
            "           ?? throw new global::System.NotSupportedException($\"Add [JsonSerializable(typeof({typeof(T).Name}))] to {context.GetType().Name}.\");\n" +
            "}\n");
        return source.ToString();
    }

    private static void AppendMethod(StringBuilder output, FrontendCommand command, string name)
    {
        var context = command.JsonContext!.ToDisplayString(TypeFormat) + ".Default";
        var token = command.Parameters.Any(static parameter => parameter.Name == "cancellationToken") ? "cancellation" : "cancellationToken";
        var parameters = command.Parameters.Select(parameter => parameter.Type.ToDisplayString(TypeFormat) + " " + Identifier(parameter.Name))
            .Append("global::System.Threading.CancellationToken " + token + " = default");
        var result = command.Result?.ToDisplayString(TypeFormat);
        output.Append("\n    /// <summary>Calls the C# command <c>").Append(Escape(command.Name)).Append("</c> (")
            .Append(Escape(command.Method.ContainingType.Name)).Append('.').Append(Escape(command.Method.Name)).Append(").</summary>\n")
            .Append("    public async global::System.Threading.Tasks.Task").Append(result is null ? "" : "<" + result + ">")
            .Append(' ').Append(name).Append('(').Append(string.Join(", ", parameters)).Append(")\n    {\n")
            .Append("        var args = new global::System.Text.Json.Nodes.JsonObject();\n");
        foreach (var parameter in command.Parameters)
        {
            output.Append("        args[").Append(Literal(parameter.Name)).Append("] = global::System.Text.Json.JsonSerializer.SerializeToNode(")
                .Append(Identifier(parameter.Name)).Append(", Info<").Append(parameter.Type.ToDisplayString(TypeFormat)).Append(">(").Append(context).Append("));\n");
        }
        var call = "await InvokeAsync(" + Literal(command.Name) + ", args, " + token + ")";
        output.Append(result is null
            ? "        " + call + ";\n"
            : "        var json = " + call + ";\n        return global::System.Text.Json.JsonSerializer.Deserialize(json, Info<" + result + ">(" + context + "))!;\n");
        output.Append("    }\n");
    }

    // Reasons a command cannot get a typed C# call; null means it can.
    private static string? Unsupported(IAssemblySymbol application, FrontendCommand command)
    {
        if (command.JsonContext is null) return "no [assembly: CommandJsonContext] is declared";
        if (!Reachable(application, command.JsonContext)) return command.JsonContext.Name + " is declared in the app, not in a shared project";
        foreach (var type in command.Parameters.Select(static parameter => parameter.Type).Concat(command.Result is null ? Array.Empty<ITypeSymbol>() : new[] { command.Result }))
        {
            var blocked = Blocked(application, type);
            if (blocked is not null) return blocked;
        }
        return null;
    }

    private static string? Blocked(IAssemblySymbol application, ITypeSymbol type)
    {
        switch (type)
        {
            case IArrayTypeSymbol array:
                return Blocked(application, array.ElementType);
            case INamedTypeSymbol named:
                if (!Reachable(application, named)) return named.Name + " is declared in the app or in a NetWiv package";
                foreach (var argument in named.TypeArguments)
                {
                    var blocked = Blocked(application, argument);
                    if (blocked is not null) return blocked;
                }
                return null;
            default:
                return type.Name + " is not a concrete wire type";
        }
    }

    // A frontend project can reference the BCL and shared libraries, but neither the desktop
    // app nor NetWiv's own packages, which carry the native desktop runtime.
    private static bool Reachable(IAssemblySymbol application, INamedTypeSymbol type)
    {
        if (type.DeclaredAccessibility != Accessibility.Public) return false;
        for (var parent = type.ContainingType; parent is not null; parent = parent.ContainingType)
            if (parent.DeclaredAccessibility != Accessibility.Public) return false;
        var assembly = type.ContainingAssembly;
        if (assembly is null || SymbolEqualityComparer.Default.Equals(assembly, application)) return false;
        return !assembly.Name.StartsWith("NetWiv.", StringComparison.Ordinal);
    }

    private static Dictionary<FrontendCommand, string> MethodNames(IReadOnlyList<FrontendCommand> commands)
    {
        string Preferred(FrontendCommand command)
            => command.Method.Name.EndsWith("Async", StringComparison.Ordinal) ? command.Method.Name : command.Method.Name + "Async";
        var duplicates = new HashSet<string>(commands.GroupBy(Preferred, StringComparer.Ordinal)
            .Where(static group => group.Count() > 1).Select(static group => group.Key), StringComparer.Ordinal);
        // Two methods with one name fall back to the external command name, which is unique.
        return commands.ToDictionary(command => command, command => duplicates.Contains(Preferred(command))
            ? Pascal(command.Name) + "Async" : Preferred(command));
    }

    private static string Pascal(string name)
    {
        var builder = new StringBuilder();
        var upper = true;
        foreach (var c in name)
        {
            if (!char.IsLetterOrDigit(c)) { upper = true; continue; }
            builder.Append(upper ? char.ToUpperInvariant(c) : c);
            upper = false;
        }
        if (builder.Length == 0 || char.IsDigit(builder[0])) builder.Insert(0, 'C');
        return builder.ToString();
    }

    private static string Identifier(string name)
        => Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? "@" + name : name;

    private static string Literal(string value)
        => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);

    private static string Escape(string value)
        => value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
