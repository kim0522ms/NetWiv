import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const inventory = JSON.parse(await readFile(path.join(root, 'compatibility/generated/upstream-tests.json'), 'utf8'));
const file = 'crates/tauri-bundler/src/bundle/category.rs';
const entry = inventory.tests.find(test => test.id === `cli:${file}:tests::category_from_string_ok`);
const commit = inventory.sources.find(source => source.role === 'cli').commit;
const source = await readFile(path.join(root, `artifacts/upstream-cli/tauri-${commit}/${file}`));
const hash = createHash('sha256').update(source).digest('hex');
if (hash !== entry.sourceSha256) throw Error('Category source differs from the pinned inventory');
const text = source.toString('utf8');
const mappings = name => Object.fromEntries([...text.slice(text.indexOf(`fn ${name}(`)).split(/\n  }/)[0]
  .matchAll(/AppCategory::(\w+) => "([^"]+)"/g)].map(match => [match[1], match[2]]));
const canonical = mappings('canonical');
const desktop = mappings('freedesktop_categories');
const macos = mappings('macos_application_category_type');
const categories = Object.keys(canonical).map(name => ({ name, canonical: canonical[name], desktop: desktop[name], macos: macos[name] }));
const aliases = [...text.matchAll(/\("([^"]+)", AppCategory::(\w+)\)/g)].map(match => ({ input: match[1], name: match[2] }));
const ok = [...text.slice(text.indexOf('fn category_from_string_ok()')).split(/\n  #\[test\]/)[0]
  .matchAll(/AppCategory::from_str\("([^"]+)"\),\s*Ok\(AppCategory::(\w+)\)/g)].map(match => ({ input: match[1], name: match[2] }));
const suggestions = [...text.matchAll(/AppCategory::from_str\("([^"]+)"\),\s*Err\(Some\("([^"]+)"\)\)/g)].map(match => ({ input: match[1], suggestion: match[2] }));
const wrong = [...text.matchAll(/AppCategory::from_str\("([^"]+)"\), Err\(None\)/g)].map(match => match[1]);
if (categories.length !== 40 || aliases.length !== 73 || ok.length !== 9 || suggestions.length !== 3 || wrong.length !== 2 || categories.some(c => !c.desktop || !c.macos))
  throw Error('Incomplete category extraction; review pinned syntax');
const notice = 'Copyright 2016-2019 Cargo-Bundle developers; Copyright 2019-2024 Tauri Programme within The Commons Conservancy; MIT OR Apache-2.0';
await writeFile(path.join(root, 'tests/NetWiv.Cli.Tests/fixtures/upstream-categories.json'), JSON.stringify({ notice, source: file, sourceSha256: hash, categories, aliases, ok, suggestions, wrong }, null, 2) + '\n');
const quote = JSON.stringify;
await writeFile(path.join(root, 'src/NetWiv.Build/Packaging/AppCategory.Generated.cs'),
  `// Generated by compatibility/scripts/generate-category-fixtures.mjs. Do not edit.\n// ${notice}\n// Source SHA-256: ${hash}\nnamespace NetWiv.Build.Packaging;\n\npublic sealed partial record AppCategory\n{\n` +
  categories.map(c => `    private static readonly AppCategory ${c.name} = new(${quote(c.name)}, ${quote(c.canonical)}, ${quote(c.desktop)}, ${quote(c.macos)});`).join('\n') +
  '\n\n    private static readonly (string Input, AppCategory Category)[] Aliases =\n    [\n' +
  aliases.map(a => `        (${quote(a.input)}, ${a.name}),`).join('\n') + '\n    ];\n}\n');
console.log(`Extracted ${categories.length} categories, ${aliases.length} aliases and four upstream test vectors`);
