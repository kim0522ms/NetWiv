    private const string ContractsSource = """
        using System.Text.Json.Serialization;
        public sealed record Greeting(string Message, int Count);
        // A custom converter has no TypeScript mapping, but the C# client reuses it as is.
        [JsonConverter(typeof(TokenConverter))] public sealed record Token(string Value);
        public sealed class TokenConverter : JsonConverter<Token> {
            public override Token Read(ref System.Text.Json.Utf8JsonReader reader, System.Type type, System.Text.Json.JsonSerializerOptions options) => new(reader.GetString()!);
            public override void Write(System.Text.Json.Utf8JsonWriter writer, Token value, System.Text.Json.JsonSerializerOptions options) => writer.WriteStringValue(value.Value);
        }
        [JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase)]
        public abstract class SharedContext : JsonSerializerContext {
            protected SharedContext() : base(null) { }
            public static SharedContext Default => throw new System.Exception("Application must not execute during export");
        }
        """;

    private const string App = """
        using System.Threading.Tasks;
        using NetWiv;
        [assembly: GenerateFrontendBindings]
        [assembly: CommandJsonContext(typeof(SharedContext))]
        public sealed record Local(int Value);
        public static class Commands {
            [Command] public static Greeting Greet(string name, AppHandle app) => throw null!;
            [Command] public static Task<string[]> List(int? limit, string @class) => throw null!;
            [Command] public static void SmokeDone(string result) { }
            [Command] public static Local Echo(Local value) => value;
        }
        """;

    [Fact]
    public void EmitsTypedCallsForSharedTypesAndExplainsSkippedCommands()
    {
        var client = Client(App);
        Assert.StartsWith("// Generated by NetWiv. Do not edit.\n", client, StringComparison.Ordinal);
        Assert.Contains("public async global::System.Threading.Tasks.Task<global::Greeting> GreetAsync(string name, global::System.Threading.CancellationToken cancellationToken = default)", client, StringComparison.Ordinal);
        Assert.Contains("args[\"name\"] = ", client, StringComparison.Ordinal);
        Assert.Contains("InvokeAsync(\"greet\", args, cancellationToken)", client, StringComparison.Ordinal);
        Assert.Contains("Task<string[]> ListAsync(int? limit, string @class, ", client, StringComparison.Ordinal);
        Assert.Contains("args[\"class\"] = global::System.Text.Json.JsonSerializer.SerializeToNode(@class, ", client, StringComparison.Ordinal);
        Assert.Contains("public async global::System.Threading.Tasks.Task SmokeDoneAsync(string result, ", client, StringComparison.Ordinal);
        Assert.DoesNotContain("AppHandle", client, StringComparison.Ordinal);
        Assert.Contains("//   echo: Local is declared in the app or in a NetWiv package", client, StringComparison.Ordinal);
        Assert.DoesNotContain("EchoAsync", client, StringComparison.Ordinal);
    }

    [Fact]
    public void GeneratedClientCompilesInAFrontendThatReferencesOnlyTheContracts() => Compile(Client(App));

    [Fact]
    public async Task GeneratedClientKeepsNestedJsonNumbersAsTextAcrossJsInterop()
    {
        const string json = """{"large":9223372036854775807,"fraction":0.1234567890123456789012345678,"nested":[9007199254740993]}""";
        var assembly = Compile(Client(EdgeApp));
        var type = assembly.GetType("NetWiv.Generated.NetWivCommands")!;
        var js = new JsonEchoModule();
        var client = Activator.CreateInstance(type, js)!;
        using var input = System.Text.Json.JsonDocument.Parse(json);
        var result = await (Task<System.Text.Json.JsonElement>)type.GetMethod("RawAsync")!
            .Invoke(client, [input.RootElement, CancellationToken.None])!;
        Assert.Equal(json, result.GetRawText());
        Assert.Equal("""{"value":""" + json + "}", js.Arguments);
    }

    private sealed class JsonEchoModule : Microsoft.JSInterop.IJSRuntime, Microsoft.JSInterop.IJSObjectReference
    {
        public string? Arguments { get; private set; }
        public ValueTask DisposeAsync() => ValueTask.CompletedTask;
        public ValueTask<TValue> InvokeAsync<TValue>(string identifier, object?[]? args) =>
            InvokeAsync<TValue>(identifier, CancellationToken.None, args);
        public ValueTask<TValue> InvokeAsync<TValue>(string identifier, CancellationToken cancellationToken, object?[]? args)
        {
            if (identifier == "import")
            {
                Assert.Equal("./netwiv.js", args![0]);
                return ValueTask.FromResult((TValue)(object)this);
            }
            Assert.Equal("invokeJson", identifier);
            Assert.Equal("raw", args![0]);
            Arguments = Assert.IsType<string>(args[1]);
            using var parsed = System.Text.Json.JsonDocument.Parse(Arguments);
            return ValueTask.FromResult((TValue)(object)parsed.RootElement.GetProperty("value").GetRawText());
        }
    }

    // Compiles the client in a frontend that references only the contracts and JS interop, and loads it.
    private static System.Reflection.Assembly Compile(string client)
    {
        var contracts = Contracts();
        var frontend = CSharpCompilation.Create("Frontend" + Guid.NewGuid().ToString("N"), [CSharpSyntaxTree.ParseText(client, new CSharpParseOptions(LanguageVersion.CSharp12))],
            PlatformReferences().Append(MetadataReference.CreateFromImage(contracts)).Append(MetadataReference.CreateFromFile(typeof(Microsoft.JSInterop.IJSRuntime).Assembly.Location)),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        Assert.DoesNotContain(frontend.GetDiagnostics(), diagnostic => diagnostic.Severity >= DiagnosticSeverity.Warning);
        // Blazor frontends may enable the trim and AOT analyzers with warnings as errors.
        var tree = frontend.SyntaxTrees.Single();
        var model = frontend.GetSemanticModel(tree);
        var unsafeCalls = tree.GetRoot().DescendantNodes().OfType<Microsoft.CodeAnalysis.CSharp.Syntax.InvocationExpressionSyntax>()
            .Select(call => model.GetSymbolInfo(call).Symbol as IMethodSymbol).Where(method => method is not null)
            .Where(method => method!.OriginalDefinition.GetAttributes().Any(attribute => attribute.AttributeClass?.Name is "RequiresUnreferencedCodeAttribute" or "RequiresDynamicCodeAttribute"))
            .Select(method => method!.ToDisplayString()).ToArray();
        Assert.Empty(unsafeCalls);
        using var stream = new MemoryStream();
        var emitted = frontend.Emit(stream);
        Assert.True(emitted.Success, string.Join("\n", emitted.Diagnostics));
        var context = new System.Runtime.Loader.AssemblyLoadContext(null, isCollectible: true);
        context.Resolving += (_, name) => name.Name == "Contracts" ? context.LoadFromStream(new MemoryStream(contracts.ToArray())) : null;
        return context.LoadFromStream(new MemoryStream(stream.ToArray()));
    }

    private static object? Invoke(Type type, string method, params object?[] arguments)
        => type.GetMethod(method, System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static)!.Invoke(null, arguments);

    // Codex review on PR #37: parameter names that match generated locals, the dispatcher's
    // numeric byte[] shape, and command names that normalize to the same method name.
    private const string EdgeApp = """
        using System.Text.Json;
        using NetWiv;
        [assembly: GenerateFrontendBindings]
        [assembly: CommandJsonContext(typeof(SharedContext))]
        public static class Commands {
            [Command] public static Greeting Locals(string args, int json, string cancellationToken) => throw null!;
            [Command] public static byte[] Bytes(byte[] data, byte[]? optional) => data;
            [Command] public static JsonElement Raw(JsonElement value) => value;
            [Command("foo-bar")] public static void Foo() { }
            [Command("foo_bar")] public static void FooAsync() { }
            [Command] public static void Invoke() { }
        }
        """;

    [Fact]
    public void KeepsLocalsBytesAndMethodNamesApartFromCommandInputs()
    {
        var client = Client(EdgeApp);
        Assert.Contains("LocalsAsync(string args, int json, string cancellationToken, global::System.Threading.CancellationToken cancellationToken2 = default)", client, StringComparison.Ordinal);
        Assert.Contains("var args2 = new global::System.Text.Json.Nodes.JsonObject();", client, StringComparison.Ordinal);
        Assert.Contains("var json2 = await this.InvokeAsync(\"locals\", args2, cancellationToken2);", client, StringComparison.Ordinal);
        Assert.Contains("args[\"data\"] = global::NetWiv.Generated.NetWivCommands.ByteArrayNode(data);", client, StringComparison.Ordinal);
        Assert.Contains("return global::NetWiv.Generated.NetWivCommands.ReadByteArray(json)!;", client, StringComparison.Ordinal);
        Assert.Contains("args[\"value\"] = global::NetWiv.Generated.NetWivCommands.ElementNode(value);", client, StringComparison.Ordinal);
        Assert.Contains(" FooBarAsync(", client, StringComparison.Ordinal);
        Assert.Contains(" FooBar2Async(", client, StringComparison.Ordinal);
        Assert.Contains(" Invoke2Async(", client, StringComparison.Ordinal);
        Compile(client);
    }

    [Fact]
    public void ByteArraysTravelAsNumberArraysLikeTheDispatcher()
    {
        var client = Compile(Client(EdgeApp));
        var type = client.GetType("NetWiv.Generated.NetWivCommands", true)!;
        var node = (System.Text.Json.Nodes.JsonNode?)Invoke(type, "ByteArrayNode", new byte[] { 0, 7, 255 });
        Assert.Equal("[0,7,255]", node!.ToJsonString());
        Assert.Null(Invoke(type, "ByteArrayNode", [null]));
        Assert.Equal(new byte[] { 1, 2, 255 }, (byte[]?)Invoke(type, "ReadByteArray", "[1,2,255]"));
        Assert.Null(Invoke(type, "ReadByteArray", "null"));
        var element = (System.Text.Json.JsonElement)Invoke(type, "ReadElement", "{\"a\":[1]}")!;
        Assert.Equal("{\"a\":[1]}", element.GetRawText());
    }

    private const string ConverterApp = """
        using NetWiv;
        [assembly: GenerateFrontendBindings]
        [assembly: CommandJsonContext(typeof(SharedContext))]
        public static class Commands { [Command] public static Token Renew(Token token) => token; }
        """;

    [Fact]
    public void AnAppThatWantsOnlyTheCSharpClientSkipsTheTypeScriptMapping()
    {
        // With script bindings requested, the converter still has no TypeScript mapping.
        Generate(DesktopApp(ConverterApp), csharpOnly: false, out var diagnostics);
        Assert.Contains(diagnostics, diagnostic => diagnostic.Id == "DTOXGEN009");

        var bindings = Bindings(ConverterApp, csharpOnly: true);
        Assert.False(bindings.HasScript);
        Assert.Contains("RenewAsync(global::Token token, ", bindings.CSharp, StringComparison.Ordinal);
        Compile(bindings.CSharp!);
        var directory = Directory.CreateTempSubdirectory("netwiv-csharp-only-").FullName;
        try { Assert.Throws<InvalidOperationException>(() => bindings.WriteTo(directory)); }
        finally { Directory.Delete(directory, true); }
    }

